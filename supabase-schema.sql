create table if not exists public.service_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id),
  reference text not null unique,
  category text not null,
  title text not null check (char_length(title) <= 80),
  description text not null check (char_length(description) <= 500),
  location text not null,
  phone text not null,
  status text not null default 'Pending' check (status in ('Pending', 'In Progress', 'Resolved')),
  priority text not null default 'Normal' check (priority in ('Low', 'Normal', 'High', 'Emergency')),
  department text not null default 'General services',
  image_url text,
  image_urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  feedback_rating integer check (feedback_rating between 1 and 5),
  feedback_comment text,
  feedback_at timestamptz
);

alter table public.service_requests enable row level security;
alter table public.service_requests add column if not exists user_id uuid references auth.users(id);
alter table public.service_requests add column if not exists image_url text;
alter table public.service_requests add column if not exists image_urls jsonb not null default '[]'::jsonb;
alter table public.service_requests add column if not exists priority text not null default 'Normal';
alter table public.service_requests add column if not exists department text not null default 'General services';
alter table public.service_requests add column if not exists feedback_rating integer;
alter table public.service_requests add column if not exists feedback_comment text;
alter table public.service_requests add column if not exists feedback_at timestamptz;
alter table public.service_requests drop constraint if exists service_requests_status_check;
update public.service_requests set status = 'Pending' where status = 'Received';
alter table public.service_requests add constraint service_requests_status_check check (status in ('Pending', 'In Progress', 'Resolved'));
alter table public.service_requests drop constraint if exists service_requests_priority_check;
alter table public.service_requests add constraint service_requests_priority_check check (priority in ('Low', 'Normal', 'High', 'Emergency'));

create table if not exists public.request_status_history (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.service_requests(id) on delete cascade,
  changed_by uuid references auth.users(id),
  previous_status text,
  new_status text not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  audience text not null default 'citizen' check (audience in ('citizen', 'admin')),
  request_id bigint references public.service_requests(id) on delete cascade,
  title text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.request_status_history enable row level security;
alter table public.notifications enable row level security;
drop policy if exists "Users can view their request history" on public.request_status_history;
create policy "Users can view their request history" on public.request_status_history for select
  using (exists (select 1 from public.service_requests r where r.id = request_id and r.user_id = auth.uid()));
drop policy if exists "Users can view their notifications" on public.notifications;
create policy "Users can view their notifications" on public.notifications for select
  using (user_id = auth.uid());

insert into storage.buckets (id, name, public) values ('request-images', 'request-images', true) on conflict (id) do nothing;

drop policy if exists "Users can view their own requests" on public.service_requests;
create policy "Users can view their own requests"
  on public.service_requests for select
  using (auth.uid() = user_id);

drop policy if exists "Users can create their own requests" on public.service_requests;
create policy "Users can create their own requests"
  on public.service_requests for insert
  with check (auth.uid() = user_id);
